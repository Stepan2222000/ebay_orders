"""Форматные проверки идентификаторов eBay — единственное место (DRY).

Используются и стадией A (ocr.py: retry-on-suspect), и save_order
(tools.py: блокеры). Логика и регэкспы живут только здесь.
"""
from __future__ import annotations

import re

# eBay order number: ровно NN-NNNNN-NNNNN (2-5-5 цифр). На всех 337 распознанных
# номерах в базе формат держится 100%. Известный режим сбоя vision (дроп ведущей
# цифры '14xxx'->'4xxx' или '1'->'I') всегда ломает формат — поэтому ловится здесь.
_ORDER_NO_RE = re.compile(r"^\d{2}-\d{5}-\d{5}$")


def is_valid_order_number(s: str) -> bool:
    return bool(_ORDER_NO_RE.fullmatch(s))


def normalize_tracking(s: str) -> str:
    """Трек к каноничному виду: только буквоцифры, верхний регистр."""
    return re.sub(r"[^A-Za-z0-9]", "", s or "").upper()


# Человекочитаемое описание тех же форматов, что проверяют функции этого модуля.
# Единственный источник для промпта стадии A (DRY): формат-подсказка живёт рядом
# с валидаторами, а не дублируется в prompt.py. Текст проверен на gpt55(low) —
# чинит дроп ведущей '1' в order_number в источнике, без фабрикации на чистых
# снимках; см. anti-fabrication-правило в конце.
IDENTIFIER_FORMATS_HINT = (
    "Формат идентификаторов (подсказка для самопроверки, НЕ повод выдумывать):\n"
    "- order_number на странице Order details имеет вид NN-NNNNN-NNNNN: две цифры, дефис, "
    "пять цифр, дефис, пять цифр (например 19-14379-54575). Перечитай по цифрам, особенно "
    "ВЕДУЩУЮ цифру каждого блока (часто '1'); средний блок — ровно 5 цифр.\n"
    "- tracking: USPS — 22 цифры (обычно 94…), UPS — '1Z' + 16 буквоцифр (всего 18).\n"
    "Если реально видишь иной формат — пиши РОВНО как на странице, не подгоняй под шаблон "
    "и не дописывай цифры."
)


def bad_tracking_reason(raw: str) -> str | None:
    """Высокоуверенная OCR-порча доминирующих перевозчиков → причина, иначе None.

    Детектим только узкие сигнатуры, где отклонение почти гарантированно
    ошибка распознавания, а не другой формат:
      - UPS:  '1Z' + 16 = 18 символов; длина 16–20 и ≠18 → порча (17/19).
      - USPS: IMpb 22 цифры, начинается на '94'; длина 20–24 и ≠22 → порча (21/23).
    Легитимные FedEx (^\\d{12}$, 20-значные), S10 (^[A-Z]{2}\\d{9}[A-Z]{2}$)
    и прочий хвост под эти границы не попадают и не флагаются.
    """
    t = normalize_tracking(raw)
    if t.startswith("1Z") and 16 <= len(t) <= 20 and len(t) != 18:
        return f"tracking looks like UPS but length {len(t)}≠18: {raw!r}"
    if t.startswith("94") and t.isdigit() and 20 <= len(t) <= 24 and len(t) != 22:
        return f"tracking looks like USPS but length {len(t)}≠22: {raw!r}"
    return None
